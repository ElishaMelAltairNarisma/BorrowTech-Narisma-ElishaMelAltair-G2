# Database Configuration
# Technology stack strictly requires PostgreSQL / Supabase for production & final submission.
# SQLite is permitted solely as a safe development fallback when no PostgreSQL instance is configured.
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

DATABASE_URL = os.environ.get('DATABASE_URL')
USE_SQLITE_FALLBACK = os.environ.get('USE_SQLITE_FALLBACK', 'False').lower() in ('true', '1', 'yes')

if DATABASE_URL:
    DATABASES = {
        'default': dj_database_url.parse(
            DATABASE_URL,
            conn_max_age=600,
            ssl_require=True if 'supabase' in DATABASE_URL or 'pooler' in DATABASE_URL else False
        )
    }
elif not USE_SQLITE_FALLBACK and os.environ.get('DB_NAME'):
    DATABASES = {
        'default': {
            'ENGINE': os.environ.get('DB_ENGINE', 'django.db.backends.postgresql'),
            'NAME': os.environ.get('DB_NAME', 'borrowtech_db'),
            'USER': os.environ.get('DB_USER', 'postgres'),
            'PASSWORD': os.environ.get('DB_PASSWORD', 'postgres'),
            'HOST': os.environ.get('DB_HOST', 'localhost'),
            'PORT': os.environ.get('DB_PORT', '5432'),
        }
    }
else:
    # Development fallback if no PostgreSQL / Supabase credentials provided in .env
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


